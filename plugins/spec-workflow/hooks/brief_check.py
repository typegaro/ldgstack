#!/usr/bin/env python3
"""PreToolUse advisory on Agent/Task: a spec-workflow subagent's prompt should be a `spec-tracker brief` pasted verbatim.
Never blocks; prints a systemMessage when the brief marker is missing (e.g. a pointer like "run brief ..." instead)."""
from __future__ import annotations

import json
import sys

MARKER = "[Generated by spec-tracker brief"
ROLES = {"spec-planner", "spec-implementer", "spec-reviewer", "spec-tester", "spec-fixer", "spec-toolsmith"}


def warning(event: dict) -> str | None:
    if event.get("tool_name") not in ("Agent", "Task"):
        return None
    tool_input = event.get("tool_input") or {}
    agent = str(tool_input.get("subagent_type") or "")
    if agent.split(":")[-1] not in ROLES or (":" in agent and not agent.startswith("spec-workflow:")):
        return None
    if MARKER in str(tool_input.get("prompt") or ""):
        return None
    return (f"spec-workflow (advisory): the {agent} prompt lacks the `{MARKER}` marker. Paste the output of "
            "`spec-tracker brief <feature> --role <role>` verbatim as the prompt (never a pointer to it), then append extra context.")


def main() -> int:
    try:
        event = json.load(sys.stdin)
    except json.JSONDecodeError:
        return 0
    message = warning(event) if isinstance(event, dict) else None
    if message:
        print(json.dumps({"systemMessage": message, "hookSpecificOutput": {"hookEventName": "PreToolUse", "additionalContext": message}}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
