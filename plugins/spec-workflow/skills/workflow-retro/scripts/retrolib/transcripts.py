"""Parse Claude Code transcripts (main session and subagents) into per-run metrics. Content is measured, never kept."""
from __future__ import annotations

import json
import re
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterator

# Relative input-token weights (Opus-class pricing ratios): a cost unit, not dollars.
WEIGHTS = {"input": 1.0, "cache_creation": 1.25, "cache_read": 0.1, "output": 5.0}
CHARS_PER_TOKEN = 4
SPEC_ROLES = {"spec-planner": "planner", "spec-implementer": "implementer", "spec-reviewer": "reviewer", "spec-tester": "tester",
              "spec-fixer": "fixer", "spec-toolsmith": "toolsmith"}
PLUGIN_DEV_TAG = "[plugin-dev]"  # in an Agent description or prompt: plugin development, not workflow cost
FEATURE = re.compile(r"\b(?:Record feature|feature)[:\s]+`?([0-9]{4})-[a-z0-9-]+")
SPEC_PATH = re.compile(r"specs/([0-9]{4})-[a-z0-9-]+\.md")
SPEC_NUMBER = re.compile(r"\b([0-9]{4})\b")
FILE_TOKEN = re.compile(r"[\w./-]+\.(?:go|ts|tsx|js|jsx|mjs|md|json|py|sql|ya?ml|css|toml|sh|txt)\b")
PERSISTED = re.compile(r"<persisted-output>\s*Output too large \(([0-9.]+)(KB|MB)\)")
EXIT_CODE = re.compile(r"^(?:Error: )?Exit code ([0-9]+)")
PLUGIN_VERSION = re.compile(r"/spec-workflow/([0-9]+\.[0-9]+\.[0-9]+)/")
SCRIPT_EXTENSIONS = r"(?:py|js|mjs|cjs|ts|sh|go)"
# A shell write (redirect or tee) whose target is a script file, e.g. `cat > /tmp/x/drive.py <<'EOF'`.
SCRIPT_WRITE = re.compile(r"(?:>>?|\btee\s+(?:-a\s+)?)\s*['\"]?([^\s'\";&|<>]+\." + SCRIPT_EXTENSIONS + r")\b")
SCRIPT_FILE = re.compile(r"\." + SCRIPT_EXTENSIONS + r"$")
BRIEF_MARKER = "[Generated by spec-tracker brief"
# Every slug segment starts with a letter, so bug-ID suffixes (<feature>-002) and UUID chunks are not features.
TRACKER_FEATURE = re.compile(r"\b([0-9]{4}(?:-[a-z][a-z0-9]*)+)\b")
ROLE_HINT = re.compile(r"\bRole:\s*(planner|implementer|reviewer|tester|fixer|toolsmith)\b")
LEADING_CD = re.compile(r"^\s*cd\s+(/[^\s;&|]+)")
NOTIFICATION = re.compile(r"<task-notification>.*?<task-id>([^<]+)</task-id>.*?<status>([^<]+)</status>(.*?)</task-notification>", re.S)

COMMAND_CATEGORIES = (
    ("tracker", re.compile(r"spec_tracker\.py|\bspec-tracker\b")),
    ("spec-cli", re.compile(r"\bspec\.py\b|\bbin/spec\b")),
    ("test", re.compile(r"\bgo test\b|playwright|\bpytest\b|\bvitest\b|\bjest\b|npm (run )?test|\bmake test\b|unittest")),
    ("lint", re.compile(r"\btsc\b|eslint|golangci|go vet|gofmt|prettier|npm run (lint|typecheck|format)|staticcheck")),
    ("build", re.compile(r"\bgo build\b|npm run build|next build|\bmake\b")),
    ("inspect", re.compile(r"\binspect\b|devinspect|cmd/inspect")),
    ("http", re.compile(r"\bcurl\b|\bhttpie\b|\bwget\b")),
    ("git", re.compile(r"\bgit\b")),
    ("read", re.compile(r"^\s*(cd [^;&|]+(&&|;)\s*)?(cat|sed -n|head|tail|grep|rg|find|ls|wc|jq)\b")),
)

# Known error messages of the workflow CLIs, classified without echoing tool output.
CLI_ERRORS = (
    ("role", re.compile(r"operation requires role|cannot hand off to|implementer cannot hand off")),
    ("gate", re.compile(r"gate failed|handoff blocked|archive blocked")),
    ("confirmation", re.compile(r"requires --parent-confirmed")),
    ("not-run-check", re.compile(r"checks not run")),
    ("open-bugs", re.compile(r"while bugs are open or assigned|bugs remain unverified")),
    ("spec-hash", re.compile(r"specification hash changed")),
    ("unknown-id", re.compile(r"unknown (requirement|bug|blocker) ID|does not exist")),
    ("usage", re.compile(r"usage: |the following arguments are required|invalid choice")),
)


def tokens_of(text: str) -> int:
    return (len(text) + CHARS_PER_TOKEN - 1) // CHARS_PER_TOKEN


def command_category(command: str) -> str:
    for name, pattern in COMMAND_CATEGORIES:
        if pattern.search(command):
            return name
    return "other"


def cli_error_class(text: str) -> str | None:
    if '"ok":false' not in text and "error:" not in text and "usage:" not in text:
        return None
    for name, pattern in CLI_ERRORS:
        if pattern.search(text):
            return name
    return "other"


def result_text(content: Any) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "".join(block.get("text", "") for block in content if isinstance(block, dict))
    return ""


@dataclass
class ToolCall:
    id: str
    name: str
    position: int  # index of the API call that issued it
    command: str = ""
    category: str = ""
    path: str = ""
    paths: list[str] = field(default_factory=list)  # files a Bash read command touches
    read_key: str = ""
    skill: str = ""
    result_tokens: int = 0
    persisted_kb: float = 0.0
    is_error: bool = False
    exit_code: int | None = None
    cli_error: str | None = None
    script: str = ""  # script file this call wrote (Write, or a shell redirect/tee); relative paths resolved against a leading cd
    script_tokens: int = 0
    features: list[str] = field(default_factory=list)  # features named in a tracker command
    target: str = ""  # SendMessage recipient
    role_hint: str = ""  # "Role: <role>" in an Agent prompt or SendMessage


@dataclass
class Run:
    id: str
    kind: str  # main | subagent
    session: str
    file: str
    agent_type: str = ""
    role: str = "parent"
    description: str = ""
    spec: int | None = None
    start: str = ""
    end: str = ""
    usage: dict[str, int] = field(default_factory=lambda: dict.fromkeys(WEIGHTS, 0))
    api_calls: int = 0
    call_weights: list[int] = field(default_factory=list)  # weighted tokens per API call, in order
    final_context: int = 0
    calls: list[ToolCall] = field(default_factory=list)
    skill_tokens: dict[str, int] = field(default_factory=dict)
    skill_positions: dict[str, int] = field(default_factory=dict)
    api_errors: Counter = field(default_factory=Counter)
    queued_messages: int = 0
    last_stop_reason: str = ""
    plugin_versions: set[str] = field(default_factory=set)
    notifications: list[str] = field(default_factory=list)
    report_tokens: list[int] = field(default_factory=list)  # main only: subagent final reports received
    brief: bool = False  # first prompt generated by `spec-tracker brief`
    plugin_dev: bool = False  # tagged PLUGIN_DEV_TAG; excluded from workflow cost
    usage_by_model: dict[str, dict[str, int]] = field(default_factory=dict)


def read_lines(path: Path) -> Iterator[dict[str, Any]]:
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            try:
                value = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(value, dict):
                yield value


def spec_of(prompt: str, description: str) -> int | None:
    """Spec from the prompt's record feature or spec path, else a 4-digit number in the short description."""
    for pattern, text in ((FEATURE, prompt), (SPEC_PATH, prompt), (FEATURE, description), (SPEC_PATH, description), (SPEC_NUMBER, description)):
        match = pattern.search(text or "")
        if match:
            return int(match.group(1))
    return None


def outside(timestamp: str, since: str, until: str) -> bool:
    return bool(timestamp) and ((bool(since) and timestamp < since) or (bool(until) and timestamp > until))


def parse_run(path: Path, kind: str, meta: dict[str, Any] | None = None, since: str = "", until: str = "") -> Run:
    """Parse one transcript. A main session is clipped to [since, until]; subagent runs are kept or dropped whole."""
    session = path.parent.parent.name if kind == "subagent" else path.stem
    run_id = path.stem.removeprefix("agent-") if kind == "subagent" else path.stem
    run = Run(run_id, kind, session, str(path))
    if meta:
        run.agent_type = str(meta.get("agentType", ""))
        run.description = str(meta.get("description", ""))
        short = run.agent_type.split(":")[-1]
        run.role = SPEC_ROLES.get(short, "other")
    usages: dict[str, dict[str, int]] = {}
    models: dict[str, str] = {}
    positions: dict[str, int] = {}
    stop_reasons: dict[str, str] = {}
    calls: dict[str, ToolCall] = {}
    skill_uses: dict[str, str] = {}
    first_prompt = ""
    timestamps: list[str] = []
    for line in read_lines(path):
        kind_of = line.get("type")
        if kind == "main" and outside(str(line.get("timestamp") or ""), since, until):
            continue
        if line.get("timestamp") and kind_of in ("user", "assistant"):
            timestamps.append(str(line["timestamp"]))
        raw = line.get("message")
        message: dict[str, Any] = raw if isinstance(raw, dict) else {}
        if kind_of == "assistant":
            if line.get("isApiErrorMessage"):
                run.api_errors[str(line.get("error") or "api_error")] += 1
                continue
            message_id = str(message.get("id") or line.get("requestId") or len(usages))
            usage = message.get("usage")
            if message_id not in usages and isinstance(usage, dict):
                positions[message_id] = len(usages)
                usages[message_id] = {
                    "input": int(usage.get("input_tokens") or 0), "output": int(usage.get("output_tokens") or 0),
                    "cache_read": int(usage.get("cache_read_input_tokens") or 0),
                    "cache_creation": int(usage.get("cache_creation_input_tokens") or 0),
                }
            if message.get("model") and message_id not in models:
                models[message_id] = str(message["model"])
            if message.get("stop_reason"):
                stop_reasons[message_id] = str(message["stop_reason"])
            position = positions.get(message_id, len(usages))
            for block in message.get("content") or []:
                if isinstance(block, dict) and block.get("type") == "tool_use" and block.get("id") not in calls:
                    calls[block["id"]] = tool_call(block, position)
                    run.plugin_versions.update(PLUGIN_VERSION.findall(json.dumps(block.get("input"))))
                    if block.get("name") == "Skill":
                        skill_uses[block["id"]] = calls[block["id"]].skill
        elif kind_of == "user":
            content = message.get("content")
            if isinstance(content, str):
                first_prompt = first_prompt or content
                if kind == "main":
                    notifications(run, content)
                continue
            for block in content or []:
                if not isinstance(block, dict):
                    continue
                if block.get("type") == "tool_result" and block.get("tool_use_id") in calls:
                    measure(calls[block["tool_use_id"]], block)
                elif block.get("type") == "text":
                    text = str(block.get("text", ""))
                    for version in PLUGIN_VERSION.findall(text):
                        run.plugin_versions.add(version)
                    source = line.get("sourceToolUseID")
                    if line.get("isMeta") and source in skill_uses:
                        name = skill_uses[source] or "unknown"
                        run.skill_tokens[name] = run.skill_tokens.get(name, 0) + tokens_of(text)
                        run.skill_positions.setdefault(name, calls[source].position)
                    elif kind == "main":
                        notifications(run, text)
                    elif not line.get("isMeta"):
                        first_prompt = first_prompt or text
        elif kind_of == "attachment":
            attachment = line.get("attachment") or {}
            if attachment.get("type") == "queued_command":
                run.queued_messages += 1
    run.calls = sorted(calls.values(), key=lambda call: (call.position, call.id))
    run.api_calls = len(usages)
    for message_id, usage in usages.items():
        by_model = run.usage_by_model.setdefault(models.get(message_id, "unknown"), dict.fromkeys(WEIGHTS, 0))
        for key in WEIGHTS:
            run.usage[key] += usage[key]
            by_model[key] += usage[key]
        run.call_weights.append(int(sum(usage[key] * weight for key, weight in WEIGHTS.items())))
    if usages:
        run.final_context = sum(list(usages.values())[-1].values())
    if stop_reasons:
        run.last_stop_reason = list(stop_reasons.values())[-1]
    if timestamps:
        run.start, run.end = min(timestamps), max(timestamps)
    if kind == "subagent":
        run.spec = spec_of(first_prompt, run.description)
        run.brief = BRIEF_MARKER in first_prompt
        run.plugin_dev = PLUGIN_DEV_TAG in first_prompt or PLUGIN_DEV_TAG in run.description
    return run


def tool_call(block: dict[str, Any], position: int) -> ToolCall:
    raw = block.get("input")
    data: dict[str, Any] = raw if isinstance(raw, dict) else {}
    call = ToolCall(str(block["id"]), str(block.get("name", "")), position)
    if call.name == "Bash":
        call.command = str(data.get("command", ""))
        call.category = command_category(call.command)
        if call.category == "read":
            call.paths = sorted(set(FILE_TOKEN.findall(call.command)))
        if call.category == "tracker":
            call.features = sorted(set(TRACKER_FEATURE.findall(call.command)))
        written = SCRIPT_WRITE.search(call.command)
        if written:
            target, cd = written.group(1), LEADING_CD.match(call.command)
            call.script = target if target.startswith("/") or not cd else f"{cd.group(1).rstrip('/')}/{target}"
            call.script_tokens = tokens_of(call.command)
    elif call.name == "Read":
        call.path = str(data.get("file_path", ""))
        call.read_key = json.dumps([call.path, data.get("offset"), data.get("limit"), data.get("pages")])
    elif call.name in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
        call.path = str(data.get("file_path") or data.get("notebook_path") or "")
        if call.name == "Write" and SCRIPT_FILE.search(call.path):
            call.script, call.script_tokens = call.path, tokens_of(str(data.get("content", "")))
    elif call.name == "Skill":
        call.skill = str(data.get("skill", ""))
    elif call.name in ("SendMessage", "Agent", "Task"):
        call.target = str(data.get("to") or data.get("agent_id") or data.get("recipient") or "")
        hint = ROLE_HINT.search(str(data.get("message") or data.get("prompt") or ""))
        call.role_hint = hint.group(1) if hint else ""
    return call


def measure(call: ToolCall, block: dict[str, Any]) -> None:
    text = result_text(block.get("content"))
    call.result_tokens = tokens_of(text)
    call.is_error = bool(block.get("is_error"))
    persisted = PERSISTED.search(text)
    if persisted:
        call.persisted_kb = float(persisted.group(1)) * (1024 if persisted.group(2) == "MB" else 1)
    exit_code = EXIT_CODE.match(text)
    if exit_code:
        call.exit_code = int(exit_code.group(1))
    if call.category in ("tracker", "spec-cli"):
        call.cli_error = cli_error_class(text)


def notifications(run: Run, text: str) -> None:
    for task_id, status, body in NOTIFICATION.findall(text):
        run.notifications.append(f"{task_id}:{status}")
        result = re.search(r"<result>(.*?)</result>", body, re.S)
        if result:
            run.report_tokens.append(tokens_of(result.group(1)))


def load(directory: Path, sessions: set[str] | None = None, since: str = "", until: str = "") -> list[Run]:
    runs: list[Run] = []
    for path in sorted(directory.glob("*.jsonl")):
        if sessions and path.stem not in sessions:
            continue
        runs.append(parse_run(path, "main", since=since, until=until))
    for path in sorted(directory.glob("*/subagents/**/agent-*.jsonl")):
        session = path.relative_to(directory).parts[0]
        if sessions and session not in sessions:
            continue
        meta_path = path.with_name(path.stem + ".meta.json")
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8")) if meta_path.is_file() else {}
        except (OSError, json.JSONDecodeError):
            meta = {}
        runs.append(parse_run(path, "subagent", meta))
    statuses: dict[str, list[str]] = {}
    for run in runs:
        for item in run.notifications:
            task_id, status = item.split(":", 1)
            statuses.setdefault(task_id, []).append(status)
    for run in runs:
        if run.kind == "subagent":
            run.notifications = statuses.get(run.id, [])
    return sorted(runs, key=lambda run: (run.start, run.id))
