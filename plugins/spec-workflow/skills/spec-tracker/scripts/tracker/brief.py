"""Generated delegation prompts (`tracker brief`): the orchestrator's template filled from durable state."""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from . import plan as plans
from . import toolkit, workspace
from .model import latest_checks, open_tool_gaps
from .store import TrackerError

SCRIPTS = Path(__file__).resolve().parents[1]
TEMPLATE = SCRIPTS.parents[1] / "spec-orchestrator" / "references" / "delegation-prompt.md"
SPEC_CLI = SCRIPTS.parents[1] / "spec-cli" / "scripts" / "spec.py"
PLANNING = SCRIPTS.parents[1] / "spec-implementer" / "references" / "planning.md"
MARKER = "[Generated by spec-tracker brief; send verbatim, append extra context below]"
BATCH = re.compile(r"^(REQ-[0-9]+)\.\.(REQ-[0-9]+)$")


def template() -> str:
    text = TEMPLATE.read_text(encoding="utf-8")
    match = re.search(r"```text\n(.*?)```", text, re.S)
    if not match:
        raise TrackerError(f"no ```text block in {TEMPLATE}")
    return match.group(1)


def toolchain(root: Path, config: dict[str, Any] | None = None, branch: str | None = None) -> str:
    try:
        commands = json.loads((root / "implementation" / "preflight.json").read_text(encoding="utf-8"))["commands"]
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise TrackerError("implementation/preflight.json is missing or malformed; create it with the user and run `spec preflight`") from error
    if config:
        commands = [workspace.rewrite(config, command, branch or config["main"], root) for command in commands]
    return "\n".join(f"  - {command}" for command in commands)


def worktree(record: dict[str, Any], config: dict[str, Any] | None, role: str) -> str:
    if config is None:
        return "none: every spec shares the project's working tree"
    tree = record.get("worktree")
    branch, main = (tree or {}).get("branch"), config["main"]
    if not tree:
        return f"not created yet; {', '.join(repo + '/' + main + '/' for repo in config['repos'])} is accepted code: read it, never edit it"
    paths = ", ".join(f"{repo}/{branch}/" for repo in tree["repos"])
    text = (f"{paths} (branch {branch}, from {tree['base']}). Work and run commands only there; Ownership globs are repo-relative "
            f"(`{tree['repos'][0]}/x/**` means `{tree['repos'][0]}/{branch}/x/**`). `<repo>/{main}/` is accepted code: never edit it.")
    if role in ("reviewer", "fixer"):
        text += " Changes under review: " + "; ".join(f"`git -C {repo}/{branch} diff {main}...HEAD`" for repo in tree["repos"])
        text += f" (each writer handoff commits a checkpoint; `git log {main}..HEAD` lists the rounds)."
    flag = record.get("rereview_required")
    if role == "reviewer" and flag:
        text += f" Focus first on the merge with {main} an agent resolved ({flag['reason']}): `git log --merges {main}..HEAD`."
    return text


def batch_ids(record: dict[str, Any], value: str) -> list[str]:
    match = BATCH.match(value)
    if not match:
        raise TrackerError("--batch must look like REQ-001..REQ-010")
    ids = [item["id"] for item in record["requirements"]]
    first, last = match.groups()
    if first not in ids or last not in ids or ids.index(first) > ids.index(last):
        raise TrackerError(f"--batch {value} is not a range of tracked requirements")
    return ids[ids.index(first): ids.index(last) + 1]


def plan_batch(record: dict[str, Any], batch: str | None) -> int | None:
    return int(batch) if batch and batch.isdigit() else None


def rerecord(record: dict[str, Any]) -> str:
    names = [item["name"] for item in latest_checks(record) if item["result"] in ("failed", "not_run")]
    return f"; failed or not_run checks, re-record these names: {', '.join(names)}" if names else ""


def scope(record: dict[str, Any], role: str, batch: str | None, final: bool) -> str:
    requirements = record["requirements"]
    if role == "planner":
        prior = plans.latest(record)
        replan = f"; replan v{prior['version']}: {record['handoff'].get('remaining', '')}" if prior else ""
        return f"plan all {len(requirements)} requirements: {', '.join(item['id'] for item in requirements)}{replan}"
    if role == "implementer":
        number = plan_batch(record, batch)
        if number is not None:
            plan = plans.latest(record)
            if plan is None:
                raise TrackerError(f"--batch {batch} names a plan batch, but no plan is stored; use --batch REQ-a..REQ-b")
            chosen = plans.batch(plan, number)
            done = {item["id"] for item in requirements if item["implemented"]}
            earlier = [rid for item in plan["batches"] if item["number"] < number for rid in item["requirements"] if rid not in done]
            pending = f"; earlier batches not yet implemented: {', '.join(earlier)}" if earlier else ""
            last = number == len(plan["batches"])
            return f"plan v{plan['version']} batch {number} of {len(plan['batches'])} (final batch: {'yes' if last else 'no'}): {', '.join(chosen['requirements'])}{pending}"
        if batch:
            return f"batch {batch} of {len(requirements)} requirements (final batch: {'yes' if final else 'no'}): {', '.join(batch_ids(record, batch))}"
        open_ids = [item["id"] for item in requirements if not item["implemented"]]
        return f"all {len(requirements)} requirements; not yet implemented: {', '.join(open_ids) or 'none'}"
    if role == "fixer":
        bugs = [f"{item['id']} ({item['severity']}) {item['title']}" for item in record["bugs"] if item["status"] == "assigned"]
        if not bugs:
            raise TrackerError(f"no assigned bugs; run `tracker bug assign {record['feature']} <BUG> --fixer fixer` first")
        return "assigned bugs: " + "; ".join(bugs) + rerecord(record)
    if role == "toolsmith":
        return "tool gaps: " + "; ".join(f"{item['id']} {item['capability']} for {', '.join(item['requirements'])}: {item['why']}"
                                         for item in open_tool_gaps(record))
    if role == "tester":
        fixed = [item["id"] for item in record["bugs"] if item["status"] == "fixed"]
        resolved = [item for item in record.get("tool_gaps", []) if item["status"] == "resolved"]
        parts = [f"retest {', '.join(fixed)} from their reproductions, then nearby behavior" if fixed else f"all {len(requirements)} requirements"]
        untested = [item["id"] for item in requirements if not item["tested"]]
        if untested and fixed:
            parts.append(f"untested: {', '.join(untested)}")
        if resolved:
            parts.append("new tools for " + ", ".join(f"{item['id']} ({item['tool']})" for item in resolved))
        return "; ".join(parts) + rerecord(record)
    return f"all {len(requirements)} requirements and the record's changed files"


def decisions(record: dict[str, Any]) -> str:
    found = [f"{item['id']}: {item['resolution']}" for item in record["blockers"] if item.get("status") == "resolved"]
    found += [f"waived {item['name']}: {item.get('user_decision', '')}" for item in record["checks"] if item["result"] == "waived"]
    found += [f"deferred {item['id']}: {item.get('user_decision', '')}" for item in record.get("tool_gaps", []) if item["status"] == "deferred"]
    found += [f"started before {', '.join(item['pending'])}: {item['user_decision']}" for item in record.get("dependency_overrides", [])]
    found += [f"{item['id']} ({item['role']} asked: {item['text']}): {item['answer']}" for item in record.get("questions", []) if item["status"] == "answered"]
    if record.get("plan_waiver"):
        found.append(f"no plan required: {record['plan_waiver']['reason']}")
    return "; ".join(found) or "none"


def next_command(tracker: str, feature: str, role: str, final: bool, batch: str | None, side: bool = False,
                 assignment: str | None = None, siblings: bool = False, pr: bool = False) -> str:
    if side:
        return f'{tracker} join {feature} --completed "..."   (you work alongside the fixer; never `handoff`)'
    handoff = f'{tracker} handoff {feature} --to {{target}} --completed "..." --remaining "..."'
    review = (f'{tracker} pr open {feature} --completed "..." --remaining "..."   (checks conflicts with main and runs the fast CI '
              "tier, then hands off to the reviewer; on a refusal fix it and run it again)") if pr else handoff.format(target="reviewer")
    if role == "implementer":
        if siblings:
            return (f'{tracker} join {feature} --assignment {assignment} --completed "..."   '
                    "(ends only your batch lane; never `handoff`: other executors are working in parallel)")
        if batch and not final:
            return "none: end without a handoff; the parent resumes you with the next batch"
        return review + "   (blocked: handoff --to parent)"
    if role == "reviewer":
        return handoff.format(target="tester") + "   (bugs, blockers, or tool gaps: --to parent)"
    if role == "tester":
        return handoff.format(target="parent")
    if role == "planner":
        return (f"{tracker} plan add {feature} --from - <<'PLAN' ... PLAN   then   " + handoff.format(target="parent"))
    if role == "fixer":
        return review + "   (blocked: handoff --to parent)"
    return handoff.format(target="tester") + "   (blocked: --to parent)"


def assignment_for(record: dict[str, Any], role: str, tracker: str, batch: str | None = None) -> dict[str, Any]:
    active = [item for item in record.get("assignments", []) if item["status"] == "active" and item["role"] == role]
    if not active:
        paths = "--read-only" if role in ("reviewer", "tester", "planner") else "--from-plan" if plans.latest(record) else "--paths <glob> [<glob> ...]"
        raise TrackerError(f"no active {role} assignment; run `{tracker} assign {record['feature']} --role {role} {paths} --parent-confirmed`")
    number = plan_batch(record, batch) if role == "implementer" and batch else None
    # Parallel executors (#78) each hold the lane assigned for their batch; never hand one batch another's lane.
    mine = next((item for item in reversed(active) if number is not None and item.get("batch") == number), None)
    if mine is None and number is not None and len(active) > 1:
        raise TrackerError(f"no lane for batch {number} among the parallel lanes ({', '.join(item['id'] for item in active)}); run "
                           f"`{tracker} assign {record['feature']} --role implementer --from-plan --batch {number} --parallel --parent-confirmed` first")
    return mine or active[-1]


def implementer_guard(record: dict[str, Any], batch: str | None, confirmed: bool, tracker: str) -> None:
    """Large specs go to the executor in batches; non-trivial specs need a plan (or a recorded waiver)."""
    feature = record["feature"]
    if confirmed:
        return
    if plans.needs_plan(record) and not plans.latest(record) and not record.get("plan_waiver"):
        raise TrackerError(f"a plan is required ({len(record['requirements'])} requirements, areas: {', '.join(sorted(plans.areas(record))) or 'unknown'}); "
                           f"hand off to the planner, or pass --parent-confirmed")
    if not batch and plans.needs_batches(record):
        plan = plans.latest(record)
        hint = f"--batch 1 (plan has {len(plan['batches'])} batches)" if plan else "--batch REQ-a..REQ-b"
        raise TrackerError(f"{feature} is large ({len(record['requirements'])} requirements, areas: {', '.join(sorted(plans.areas(record))) or 'unknown'}); "
                           f"brief one batch at a time: `{tracker} brief {feature} --role implementer {hint}`, or pass --parent-confirmed")


def plan_text(record: dict[str, Any], role: str, batch: str | None, tracker: str) -> str:
    plan = plans.latest(record)
    show = f"{tracker} plan show {record['feature']}"
    if role == "planner":
        return f"write it from the template and mandatory checks in {PLANNING} (read it first)"
    if role not in ("implementer", "reviewer", "fixer"):
        return "not shown to this role; work from the spec"
    if plan is None:
        return "none"
    stale = plans.stale_text(plan)
    warning = f"\n  WARNING: {stale}" if stale else ""
    if role == "implementer":
        number = plan_batch(record, batch)
        if number is None and len(plan["batches"]) > 1 and batch:
            return f"follow `{show}` for the requirements of this range{warning}"
        body = plans.brief_text(plan, number if number is not None else (1 if len(plan["batches"]) == 1 else None), show)
        return f"v{plan['version']}, follow it literally:{warning}\n" + "\n".join(f"  {line}" if line else "" for line in body.splitlines())
    if role in ("reviewer", "fixer"):
        return f"v{plan['version']}: `{show}` (what the executor was told to build){warning}"
    return "not shown to this role; work from the spec"


FILE = re.compile(r"`([^`\s]+/[^`\s]+)`")


def batch_files(record: dict[str, Any], batch: str | None) -> list[str]:
    """Paths the plan batch names in backticks (minus globs and `:line` suffixes), for the first-turn read list."""
    plan = plans.latest(record)
    number = plan_batch(record, batch)
    if plan is None or (number is None and len(plan["batches"]) != 1):
        return []
    text = plans.batch(plan, number if number is not None else 1)["text"]
    found = [re.sub(r":[0-9]+(?:-[0-9]+)?$", "", item) for item in FILE.findall(text)]
    return list(dict.fromkeys(item for item in found if "*" not in item and not item.startswith(("-", "http"))))[:8]


def first_turn(record: dict[str, Any], role: str, batch: str | None, spec_command: str) -> str:
    """One parallel read turn the agent issues right after `claim` (turns.batching)."""
    reads = [f"`{spec_command}` (requirements)", f"`tracker requirement list {record['feature']}`"]
    files = batch_files(record, batch) if role == "implementer" else []
    if files:
        reads.append("these batch files: " + ", ".join(files))
    elif role == "fixer":
        reads.append("the files named in each bug's reproduction and evidence")
    else:
        reads.append("every file you already know you need")
    return "in ONE message (parallel tool calls), read " + "; ".join(reads)


def render(root: Path, record: dict[str, Any], role: str, batch: str | None, final: bool, others: list[dict[str, Any]],
           confirmed: bool = False) -> str:
    feature = record["feature"]
    tracker = f"python3 {SCRIPTS / 'spec_tracker.py'}"
    side = record.get("side_role") == role
    if record["current_role"] != role and not side:
        raise TrackerError(f"the record is with the {record['current_role']}; run `{tracker} handoff {feature} --to {role} ...` first")
    if batch and role != "implementer":
        raise TrackerError("--batch applies only to implementer briefs")
    if role == "implementer":
        implementer_guard(record, batch, confirmed, tracker)
    final = final or bool(batch and plan_batch(record, batch) is not None and plans.latest(record)
                          and plan_batch(record, batch) == len(plans.latest(record)["batches"]))
    own = assignment_for(record, role, tracker, batch)
    try:
        config = workspace.load(root)
    except workspace.WorkspaceError as error:
        raise TrackerError(str(error)) from error
    tree = record.get("worktree")
    if tree:
        # Other specs edit their own worktrees; only shared-tree lanes (and this spec's parallel executors) are off limits.
        others = [item for item in others if not item.get("branch")]
    siblings = [item for item in record.get("assignments", []) if item["status"] == "active" and item["role"] == role and item["id"] != own["id"]]
    foreign = sorted({glob for item in others + siblings for glob in item.get("paths", [])})
    ownership = f"edit only {', '.join(own['paths'])}" if own["paths"] else "read-only: edit nothing in the project"
    carved = [f"{item['glob']} (carved out to {item['to']}, {item['feature']})" for item in own.get("carved", [])]
    ownership += f", except {', '.join(carved)}" if carved else ""
    ownership += f"; do not touch {', '.join(foreign)}" if foreign else ""
    kit = toolkit.summary(root, tree["branch"] if tree else None)
    gaps = [f"{item['id']} {item['capability']} for {', '.join(item['requirements'])}" for item in open_tool_gaps(record)]
    values = {
        "marker": MARKER, "spec_path": record["specification"]["path"], "spec_cli": f"python3 {SPEC_CLI}",
        "spec_id": str(int(feature.split("-", 1)[0])) if feature[:4].isdigit() else feature,
        "role": role, "feature": feature, "status": record["status"], "current_role": record["current_role"],
        "scope": scope(record, role, batch, final),
        "first_turn": first_turn(record, role, batch, f"python3 {SPEC_CLI} show {int(feature[:4]) if feature[:4].isdigit() else feature} --effective"), "decisions": decisions(record), "plan": plan_text(record, role, batch, tracker),
        "assignment": f"{own['id']} ({own['role']})", "claim_command": f"{tracker} claim {own['id']}",
        "ownership": ownership, "toolchain": toolchain(root, config, tree["branch"] if tree else None), "tracker": tracker,
        "worktree": worktree(record, config, role), "risk": record.get("risk", "normal"),
        "toolkit": "\n".join(f"  - {line}{' (stale)' if line.split(' ', 1)[0] in kit['stale'] else ''}" for line in kit["lines"]) or "  none registered",
        "gaps": "; ".join(gaps) or "none", "next_command": next_command(tracker, feature, role, final, batch, side, own["id"], bool(siblings) and role == "implementer",
                                                                   bool(tree and config)),
    }
    try:
        return template().format(**values).rstrip() + "\n"
    except KeyError as error:
        raise TrackerError(f"delegation-prompt.md uses an unknown placeholder {error}") from error
