#!/usr/bin/env python3
"""Generate the OpenCode agents (opencode/agents/*.md) from the Claude Code agents (agents/*.md), and keep the root
package.json version equal to .claude-plugin/plugin.json. The Claude agents are the source; never edit the output.

Usage: build.py [--check]   (--check exits 1 when an output is stale, for tests and CI)"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLUGIN = HERE.parent
REPO = PLUGIN.parent.parent
SOURCE = PLUGIN / "agents"
OUTPUT = HERE / "agents"
WRITE_TOOLS = {"Edit", "Write"}
READ_ACTIONS = ("read", "glob", "grep", "skill", "shell")
HEADER = "<!-- Generated by opencode/build.py from agents/{name}.md; edit the source, then rerun it. -->\n\n"


def frontmatter(text: str) -> tuple[dict[str, str], str]:
    match = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not match:
        raise ValueError("agent file has no frontmatter")
    fields = dict(line.split(": ", 1) for line in match.group(1).splitlines() if ": " in line)
    return fields, match.group(2).lstrip("\n")


def translate(body: str) -> str:
    """Claude Code names → OpenCode names. The plugin's tool-mapping note covers the remaining tool differences."""
    return body.replace("spec-workflow:", "").replace("with the Skill tool", "with the `skill` tool")


def render(source: Path) -> str:
    fields, body = frontmatter(source.read_text(encoding="utf-8"))
    tools = {tool.strip() for tool in fields.get("tools", "").split(",")}
    actions = list(READ_ACTIONS) + (["edit"] if tools & WRITE_TOOLS else [])
    rules = [("*", "deny")] + [(action, "allow") for action in actions]
    lines = ["---", f"description: {fields['description']}", "mode: subagent", "permissions:"]
    for action, effect in rules:
        lines += [f'  - action: "{action}"', '    resource: "*"', f"    effect: {effect}"]
    return "\n".join(lines) + "\n---\n" + HEADER.format(name=source.stem) + translate(body)


def outputs() -> dict[Path, str]:
    found = {OUTPUT / source.name: render(source) for source in sorted(SOURCE.glob("*.md"))}
    version = json.loads((PLUGIN / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))["version"]
    package = REPO / "package.json"
    data = json.loads(package.read_text(encoding="utf-8"))
    data["version"] = version
    found[package] = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    return found


def main() -> int:
    check = "--check" in sys.argv[1:]
    expected = outputs()
    stale = [path for path, text in expected.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    extra = [path for path in OUTPUT.glob("*.md") if path not in expected]
    if check:
        for path in stale + extra:
            print(f"stale: {path.relative_to(REPO)} (run plugins/spec-workflow/opencode/build.py)", file=sys.stderr)
        return 1 if stale or extra else 0
    OUTPUT.mkdir(exist_ok=True)
    for path in stale:
        path.write_text(expected[path], encoding="utf-8")
    for path in extra:
        path.unlink()
    print(f"updated {len(stale)} file(s), removed {len(extra)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
