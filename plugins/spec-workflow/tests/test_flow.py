"""0.16.0: the simple flow - `tracker next` for the parent, `tracker ASSIGN-... <verb>` for agents, `tracker merge`."""
from __future__ import annotations

import re
import unittest

from test_prs import CI, HOOKS, PrCase
from test_workflow import FEATURE
from test_worktrees import OTHER


class FlowTest(PrCase):
    workspace: dict = {"ci": CI, "hooks": HOOKS, "verify": "parallel"}

    def setUp(self) -> None:
        super().setUp()
        (self.root / "specs" / f"{OTHER}.md").unlink()

    def next(self) -> list[dict]:
        return self.tracker("next")["result"]["actions"]

    def launched(self, actions: list[dict], role: str) -> str:
        action = next(item for item in actions if item["do"] == "launch" and item["role"] == role and item["feature"] == FEATURE)
        self.assertIn("[Generated by spec-tracker brief", action["brief"])
        found = re.search(r"Assignment: (ASSIGN-\S+)", action["brief"])
        assert found is not None
        return found.group(1)

    def agent(self, assignment: str, *words: str, succeeds: bool = True) -> dict:
        return self.tracker(assignment, *words, succeeds=succeeds)

    def test_a_spec_goes_from_draft_to_main_with_next_and_verbs(self) -> None:
        builder = self.launched(self.next(), "implementer")
        self.assertEqual(self.next(), [], "an issued brief is not issued twice")
        self.branch_file(FEATURE, "internal/b.go")
        self.agent(builder, "done", "built the behavior")
        record = self.record()
        self.assertEqual((record["status"], record["requirements"][0]["implemented"]), ("ready_for_verify", True))

        actions = self.next()
        reviewer, tester = self.launched(actions, "reviewer"), self.launched(actions, "tester")
        self.agent(reviewer, "bug", "Typo in the error", "--repro", "go test ./internal", "--got", "erorr", "--severity", "low")
        self.agent(reviewer, "done", "reviewed internal/")
        self.agent(tester, "tested", "all", "observed the behavior")
        self.agent(tester, "done", "drove the API")
        self.assertEqual(self.record()["status"], "bugs_found")

        fixer = self.launched(self.next(), "fixer")
        self.branch_file(FEATURE, "internal/b_test.go", "package branch\n")
        self.agent(fixer, "fixed", f"BUG-{FEATURE}-001", "fixed the typo", "--test", "go test ./internal")
        result = self.agent(fixer, "done", "fixed the typo")["result"]
        self.assertTrue(result["verify"].startswith("light"), result)

        retester = self.launched(self.next(), "tester")
        self.agent(retester, "retest", f"BUG-{FEATURE}-001", "ok", "the message is right")
        self.agent(retester, "tested", "all", "observed again")
        self.agent(retester, "done", "retested")
        self.assertEqual(self.record()["status"], "ready_for_acceptance")

        merge = next(item for item in self.next() if item["do"] == "merge")
        self.assertEqual(merge["command"], "tracker merge")
        self.assertEqual(self.tracker("merge")["result"]["result"], "merged")
        self.assertEqual(self.record(archived=True)["pr"]["state"], "merged")

    def test_agent_mistakes_get_short_answers(self) -> None:
        builder = self.launched(self.next(), "implementer")
        self.assertIn("unknown assignment", self.agent("ASSIGN-nope", "done", "x", succeeds=False)["error"]["message"])
        error = self.agent(builder, "bug", "x", succeeds=False)["error"]["message"]
        self.assertIn("--repro", error)
        self.branch_file(FEATURE, "internal/b.go")
        self.agent(builder, "done", "built it")
        self.assertIn("was released", self.agent(builder, "done", "again", succeeds=False)["error"]["message"])


if __name__ == "__main__":
    unittest.main()
